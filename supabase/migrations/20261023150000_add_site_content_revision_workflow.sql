  CREATE TABLE IF NOT EXISTS public.site_content_revisions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content jsonb NOT NULL,
    action text NOT NULL CHECK (action IN ('draft_saved', 'published', 'restored_as_draft', 'discarded')),
    actor_id uuid REFERENCES public.admin_users(id) ON DELETE SET NULL,
    actor_label text NOT NULL DEFAULT 'Administrator',
    created_at timestamptz NOT NULL DEFAULT now()
  );

  CREATE INDEX IF NOT EXISTS site_content_revisions_created_at_idx
    ON public.site_content_revisions (created_at DESC);

  ALTER TABLE public.site_content_revisions ENABLE ROW LEVEL SECURITY;
  REVOKE ALL ON TABLE public.site_content_revisions FROM anon, authenticated, PUBLIC;
  GRANT SELECT, INSERT ON TABLE public.site_content_revisions TO service_role;

  INSERT INTO public.site_content_revisions (content, action, actor_id, actor_label, created_at)
  SELECT
    cms.published_content,
    'published',
    cms.published_by,
    COALESCE(admin.email, 'Administrator'),
    COALESCE(cms.published_at, cms.updated_at)
  FROM public.site_content_cms AS cms
  LEFT JOIN public.admin_users AS admin ON admin.id = cms.published_by
  WHERE cms.id = true
    AND cms.published_content IS NOT NULL
    AND NOT EXISTS (
      SELECT 1
      FROM public.site_content_revisions AS revision
      WHERE revision.action = 'published'
        AND revision.content = cms.published_content
    );

  CREATE OR REPLACE FUNCTION public.save_site_content_draft(
    p_content jsonb,
    p_actor_id uuid,
    p_actor_label text
  )
  RETURNS jsonb
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path = pg_catalog, public
  AS $$
  DECLARE
    saved_row public.site_content_cms%ROWTYPE;
    existing_row public.site_content_cms%ROWTYPE;
    had_existing boolean;
    revision_id bigint;
  BEGIN
    SELECT * INTO existing_row
    FROM public.site_content_cms
    WHERE id = true
    FOR UPDATE;
    had_existing := FOUND;

    INSERT INTO public.site_content_cms (id, draft_content, updated_by, updated_at)
    VALUES (true, p_content, p_actor_id, now())
    ON CONFLICT (id) DO UPDATE
    SET draft_content = EXCLUDED.draft_content,
        updated_by = EXCLUDED.updated_by,
        updated_at = EXCLUDED.updated_at
    RETURNING * INTO saved_row;

    IF NOT had_existing OR existing_row.draft_content IS DISTINCT FROM p_content THEN
      INSERT INTO public.site_content_revisions (content, action, actor_id, actor_label)
      VALUES (p_content, 'draft_saved', p_actor_id, COALESCE(NULLIF(trim(p_actor_label), ''), 'Administrator'))
      RETURNING id INTO revision_id;
    END IF;

    RETURN jsonb_build_object('content', saved_row.draft_content, 'revision_id', revision_id);
  END;
  $$;

  CREATE OR REPLACE FUNCTION public.publish_site_content(p_actor_id uuid)
  RETURNS jsonb
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path = pg_catalog, public
  AS $$
  DECLARE
    published_row public.site_content_cms%ROWTYPE;
    actor_label text;
    revision_id bigint;
  BEGIN
    SELECT email INTO actor_label FROM public.admin_users WHERE id = p_actor_id;

    UPDATE public.site_content_cms
    SET published_content = draft_content,
        published_by = p_actor_id,
        published_at = now()
    WHERE id = true
      AND draft_content IS NOT NULL
    RETURNING * INTO published_row;

    IF NOT FOUND THEN
      RETURN NULL;
    END IF;

    INSERT INTO public.site_content_revisions (content, action, actor_id, actor_label)
    VALUES (published_row.published_content, 'published', p_actor_id, COALESCE(NULLIF(trim(actor_label), ''), 'Administrator'))
    RETURNING id INTO revision_id;

    RETURN jsonb_build_object(
      'content', published_row.published_content,
      'published_at', published_row.published_at,
      'revision_id', revision_id
    );
  END;
  $$;

  CREATE OR REPLACE FUNCTION public.restore_site_content_revision(
    p_revision_id bigint,
    p_actor_id uuid,
    p_actor_label text
  )
  RETURNS jsonb
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path = pg_catalog, public
  AS $$
  DECLARE
    selected_revision public.site_content_revisions%ROWTYPE;
    revision_id bigint;
  BEGIN
    SELECT * INTO selected_revision
    FROM public.site_content_revisions
    WHERE id = p_revision_id;

    IF NOT FOUND THEN
      RETURN NULL;
    END IF;

    INSERT INTO public.site_content_cms (id, draft_content, updated_by, updated_at)
    VALUES (true, selected_revision.content, p_actor_id, now())
    ON CONFLICT (id) DO UPDATE
    SET draft_content = EXCLUDED.draft_content,
        updated_by = EXCLUDED.updated_by,
        updated_at = EXCLUDED.updated_at;

    INSERT INTO public.site_content_revisions (content, action, actor_id, actor_label)
    VALUES (selected_revision.content, 'restored_as_draft', p_actor_id, COALESCE(NULLIF(trim(p_actor_label), ''), 'Administrator'))
    RETURNING id INTO revision_id;

    RETURN jsonb_build_object('content', selected_revision.content, 'revision_id', revision_id);
  END;
  $$;

  CREATE OR REPLACE FUNCTION public.discard_site_content_draft(p_actor_id uuid, p_actor_label text)
  RETURNS jsonb
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path = pg_catalog, public
  AS $$
  DECLARE
    current_row public.site_content_cms%ROWTYPE;
    revision_id bigint;
  BEGIN
    SELECT * INTO current_row
    FROM public.site_content_cms
    WHERE id = true
    FOR UPDATE;

    IF NOT FOUND OR current_row.published_content IS NULL THEN
      RETURN NULL;
    END IF;

    IF current_row.draft_content IS NOT NULL AND current_row.draft_content IS DISTINCT FROM current_row.published_content THEN
      INSERT INTO public.site_content_revisions (content, action, actor_id, actor_label)
      VALUES (current_row.draft_content, 'discarded', p_actor_id, COALESCE(NULLIF(trim(p_actor_label), ''), 'Administrator'))
      RETURNING id INTO revision_id;
    END IF;

    UPDATE public.site_content_cms
    SET draft_content = published_content,
        updated_by = p_actor_id,
        updated_at = now()
    WHERE id = true
    RETURNING * INTO current_row;

    RETURN jsonb_build_object('content', current_row.draft_content, 'revision_id', revision_id);
  END;
  $$;

